                        value = Array.from(sel.selectedOptions).map(o => (o.textContent || o.label || o
                            .value).trim()).filter(Boolean).join(', ');
                    } else {
                        const opt = sel.selectedOptions && sel.selectedOptions[0] ? sel.selectedOptions[
                            0] : null;
                        value = (opt ? (opt.textContent || opt.label || opt.value) : sel.value || '')
                            .trim();
                    }
                    if (value) items.push({
                        label,
                        value
                    });
                    return;
                }

                const label = getElementorFieldLabel(el);
                const value = (el.value || el.textContent || '').trim();
                if (value) items.push({
                    label,
                    value
                });
            });

            return items;
        }

